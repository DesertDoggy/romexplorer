//! The `KEY=VALUE` file shape this project uses for anything that must be readable and
//! editable by hand without a parser: `assets/api.env` (provider credentials), the setup
//! file `romexplorer_server --init-from-config` reads, and `data/database.env` (the stored
//! connection settings).
//!
//! One reader, because there were two byte-identical copies of this loop -- in
//! `env_creds::ApiCredentials::parse` and `api::setup::SetupFile::parse` -- and a third was
//! about to be written. Each caller still does its own validation; only the lexing is shared.
//!
//! Syntax: `KEY=VALUE` per line, `#` comments, blank lines skipped, an optional `export `
//! prefix ignored, and matching single or double quotes stripped from the value. Keys are
//! lowercased, so the file may be written in either case.

use std::collections::HashMap;
use std::path::Path;

pub type Values = HashMap<String, String>;

pub fn parse(text: &str) -> Values {
    let mut values = HashMap::new();
    for raw in text.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line = line.strip_prefix("export ").unwrap_or(line);
        let Some((key, value)) = line.split_once('=') else { continue };
        let key = key.trim().to_ascii_lowercase();
        let mut value = value.trim();
        if value.len() >= 2 && ((value.starts_with('"') && value.ends_with('"')) || (value.starts_with('\'') && value.ends_with('\''))) {
            value = &value[1..value.len() - 1];
        }
        if !key.is_empty() {
            values.insert(key, value.to_string());
        }
    }
    values
}

/// The file's values, or an empty set if it isn't there. A missing file is not an error:
/// every caller here treats absence as "nothing configured yet".
pub fn load(path: &Path) -> std::io::Result<Values> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(parse(&text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Values::new()),
        Err(e) => Err(e),
    }
}

/// Writes `pairs` in the same syntax, owner-only. These files hold passwords, so the mode
/// matters as much as the contents -- the same treatment `api::setup::ensure_server_token`
/// gives the bearer token. Values are written with double quotes so trailing spaces and `#`
/// survive a round trip; a value containing a double quote is rejected rather than mangled.
pub fn write(path: &Path, header: &str, pairs: &[(&str, String)]) -> std::io::Result<()> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let mut out = String::new();
    for line in header.lines() {
        out.push_str("# ");
        out.push_str(line);
        out.push('\n');
    }
    out.push('\n');
    for (key, value) in pairs {
        if value.contains('"') || value.contains('\n') {
            return Err(std::io::Error::new(std::io::ErrorKind::InvalidInput, format!("{key} cannot contain a quote or newline")));
        }
        out.push_str(&format!("{key}=\"{value}\"\n"));
    }
    romexplorer_types::private_file::write(path, out.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_the_shapes_the_existing_files_use() {
        let v = parse("# a comment\n\nexport DB_PORT=3307\ndb_user = 'root'\ndb_password=\"p w\"\nbare\n");
        assert_eq!(v.get("db_port").map(String::as_str), Some("3307"));
        assert_eq!(v.get("db_user").map(String::as_str), Some("root"), "quotes stripped, key lowercased");
        assert_eq!(v.get("db_password").map(String::as_str), Some("p w"), "spaces inside quotes kept");
        assert!(!v.contains_key("bare"), "a line with no = is skipped, not half-parsed");
    }

    #[test]
    fn a_missing_file_is_empty_not_an_error() {
        assert!(load(Path::new("/nonexistent/romexplorer/database.env")).expect("missing is ok").is_empty());
    }

    #[test]
    fn round_trips_through_write() {
        let dir = std::env::temp_dir().join(format!("rx_env_file_{}", std::process::id()));
        let path = dir.join("database.env");
        write(&path, "generated by a test", &[("db_port", "3309".into()), ("db_password", "s3cret with spaces".into())]).expect("write");
        let back = load(&path).expect("load");
        assert_eq!(back.get("db_port").map(String::as_str), Some("3309"));
        assert_eq!(back.get("db_password").map(String::as_str), Some("s3cret with spaces"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_eq!(std::fs::metadata(&path).expect("stat").permissions().mode() & 0o777, 0o600, "a file holding a password must be owner-only");
        }
        let _ = std::fs::remove_dir_all(&dir);
    }
}
